export function searchDictionary(query = '', fieldFilter = 'all') {
  const q = query.trim().toLowerCase();
  return LEGAL_DICTIONARY.filter(item => {
    const matchesField = fieldFilter === 'all' || item.field.toLowerCase().includes(fieldFilter.toLowerCase());
    if (!matchesField) return false;

    if (!q) return true;
    return (
      item.term.toLowerCase().includes(q) ||
      item.termBn.toLowerCase().includes(q) ||
      item.transliteration.toLowerCase().includes(q) ||
      item.definitionEn.toLowerCase().includes(q) ||
      item.definitionBn.toLowerCase().includes(q) ||
      (item.statutoryReference && item.statutoryReference.toLowerCase().includes(q))
    );
  });
}
