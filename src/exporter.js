/**
 * LexNote Note Exporter & Document Generator
 * Supports PDF (Printable Stationery), DOCX (Word formatted), Markdown, and Plain Text.
 */

export function exportNoteAsText(note) {
  const content = `=======================================================
LEXNOTE — MY AI LAW NOTEBOOK
=======================================================
Title:       ${note.title || 'Untitled Note'}
Subject:     ${note.subjectName || note.subjectId || 'N/A'}
Semester:    ${note.semester || 'N/A'}
Chapter:     ${note.chapter || 'N/A'}
Topic:       ${note.topic || 'N/A'}
Lecture:     ${note.lectureNo || 'N/A'} (${note.lectureDate || 'Undated'})
Tags:        ${(note.tags || []).join(', ')}
Created:     ${new Date(note.createdAt || Date.now()).toLocaleString()}
=======================================================

--- POLISHED LAW NOTE ---
${note.structuredNote || 'No structured note text.'}

=======================================================
--- RAW LECTURE TRANSCRIPT ---
${note.rawTranscript || 'No raw transcript recorded.'}

=======================================================
--- SUMMARY ---
${note.summary || 'No summary recorded.'}
`;

  downloadBlob(content, `${slugify(note.title || 'lexnote')}.txt`, 'text/plain;charset=utf-8');
}

export function exportNoteAsMarkdown(note) {
  const md = `# ${note.title || 'Untitled Law Note'}

> **Subject:** ${note.subjectName || note.subjectId || 'Law'} · **Semester:** ${note.semester || 'LLB'} · **Date:** ${note.lectureDate || new Date().toISOString().split('T')[0]}  
> **Tags:** ${(note.tags || []).map(t => `\`#${t}\``).join(' ')}

---

## Polished Law Note
${note.structuredNote || '*No structured note available.*'}

---

## Executive Summary
${note.summary || '*No summary available.*'}

---

## Original Lecture Transcript
\`\`\`
${note.rawTranscript || 'No raw transcript recorded.'}
\`\`\`

---
*Generated by LexNote — My AI Law Notebook*
`;

  downloadBlob(md, `${slugify(note.title || 'lexnote')}.md`, 'text/markdown;charset=utf-8');
}

